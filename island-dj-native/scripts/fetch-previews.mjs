// Fetch a 30s audio preview URL for each genre point via Apple's iTunes Search
// API and write them to src/data/previews.generated.js.
//
//   node scripts/fetch-previews.mjs
//
// iTunes Search is free and needs NO auth (no Spotify secret, unlike covers) —
// it just returns a `previewUrl` (30s AAC clip on Apple's CDN) per track. We
// keep the URLs and stream them at runtime; nothing audio is bundled. Rerun any
// time to fill gaps. No npm deps (Node 18+ built-in fetch/fs).
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { GENRE_POINTS } from '../src/data/genres.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const OUT = resolve(ROOT, 'src/data/previews.generated.js')

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

// normalize for fuzzy matching: lowercase, strip diacritics + punctuation/spaces
const norm = (s) =>
  (s ?? '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]/g, '')

// iTunes rate-limits to ~20 req/min, so throttle and back off on 403. We pull a
// few candidates and pick the one whose ARTIST matches — limit=1 often returns a
// karaoke/piano cover or remix by someone else (e.g. "Ivy" → a piano cover).
async function findPreview(artist, song) {
  const term = encodeURIComponent(`${artist} ${song}`)
  const url = `https://itunes.apple.com/search?term=${term}&media=music&entity=song&limit=25&country=US`
  for (let attempt = 0; attempt < 2; attempt++) {
    const res = await fetch(url)
    if (res.status === 403 || res.status === 429) {
      await sleep(5000) // backed off; retry once
      continue
    }
    if (!res.ok) throw new Error(`search ${res.status}`)
    const all = (await res.json())?.results ?? []
    const results = all.filter((r) => r.previewUrl) // only playable candidates
    if (!results.length) return { previewUrl: null, matched: '(no preview)' }
    const wantA = norm(artist)
    const wantS = norm(song)
    let best = null
    let bestScore = -1
    for (const r of results) {
      const a = norm(r.artistName)
      const t = norm(r.trackName)
      const aMatch = a.includes(wantA) || wantA.includes(a)
      const tMatch = t.includes(wantS) || wantS.includes(t)
      const score = (aMatch ? 2 : 0) + (tMatch ? 1 : 0)
      if (score > bestScore) {
        bestScore = score
        best = r
      }
    }
    if (bestScore < 2) best = results[0] // no artist match anywhere → take the top hit
    const flagged = bestScore < 2 ? ' (?)' : ''
    return { previewUrl: best?.previewUrl ?? null, matched: `${best.artistName} – ${best.trackName}${flagged}` }
  }
  throw new Error('rate-limited (403/429) after retry')
}

async function main() {
  console.log('Fetching', GENRE_POINTS.length, 'iTunes previews…\n')
  const entries = []
  for (let i = 0; i < GENRE_POINTS.length; i++) {
    const g = GENRE_POINTS[i]
    const idx = String(i).padStart(2, '0')
    try {
      const { previewUrl, matched } = await findPreview(g.artist, g.song)
      entries.push(previewUrl)
      const flag = previewUrl ? '' : '  ⚠ no preview'
      console.log(`  ${idx} ${g.artist} – ${g.song}  →  ${matched}${flag}`)
    } catch (e) {
      entries.push(null)
      console.warn(`  ${idx} ${g.artist} – ${g.song}: ${e.message}`)
    }
    await sleep(2500) // stay under the rate limit
  }

  const lines = entries.map((u) => (u ? `  ${JSON.stringify(u)},` : '  null,'))
  writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/fetch-previews.mjs — do not edit.\n` +
      `// One 30s iTunes preview URL per GENRE_POINTS index (null = none → no audio\n` +
      `// for that cover). Streamed at runtime; nothing is bundled.\n` +
      `export const PREVIEWS = [\n${lines.join('\n')}\n]\n`,
  )
  const ok = entries.filter(Boolean).length
  console.log(`\nDone: ${ok}/${entries.length} previews → ${OUT.replace(ROOT + '/', '')}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})

// Fetch real Spotify album covers for each genre point and bundle them.
//
//   node scripts/fetch-covers.mjs
//
// Reads SPOTIFY_CLIENT_ID / SPOTIFY_CLIENT_SECRET from island-dj-native/.env
// (Client Credentials flow — app-only, no user login, no Premium). Downloads a
// cover per genre into assets/covers/ and writes src/data/covers.generated.js.
// No npm deps (Node 18+ built-in fetch/fs). The secret never ships in the app.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { GENRE_POINTS } from '../src/data/genres.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const COVERS_DIR = resolve(ROOT, 'assets/covers')
const OUT = resolve(ROOT, 'src/data/covers.generated.js')

function loadEnv() {
  const env = { ...process.env }
  const envPath = resolve(ROOT, '.env')
  if (existsSync(envPath)) {
    for (const line of readFileSync(envPath, 'utf8').split('\n')) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
      if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '')
    }
  }
  return env
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

async function getToken(id, secret) {
  const res = await fetch('https://accounts.spotify.com/api/token', {
    method: 'POST',
    headers: {
      Authorization: 'Basic ' + Buffer.from(`${id}:${secret}`).toString('base64'),
      'Content-Type': 'application/x-www-form-urlencoded',
    },
    body: 'grant_type=client_credentials',
  })
  if (!res.ok) throw new Error(`token ${res.status}: ${await res.text()}`)
  return (await res.json()).access_token
}

async function findCover(token, artist, song) {
  const q = encodeURIComponent(`${artist} ${song}`)
  const res = await fetch(`https://api.spotify.com/v1/search?q=${q}&type=track&limit=1&market=US`, {
    headers: { Authorization: `Bearer ${token}` },
  })
  if (!res.ok) throw new Error(`search ${res.status}: ${await res.text()}`)
  const track = (await res.json())?.tracks?.items?.[0]
  const images = track?.album?.images ?? []
  // prefer ~300px (images are ordered largest→smallest); fall back to largest
  return images[1]?.url ?? images[0]?.url ?? null
}

async function main() {
  const env = loadEnv()
  const id = env.SPOTIFY_CLIENT_ID
  const secret = env.SPOTIFY_CLIENT_SECRET
  if (!id || !secret) {
    console.error('Missing SPOTIFY_CLIENT_ID / SPOTIFY_CLIENT_SECRET (put them in island-dj-native/.env)')
    process.exit(1)
  }

  mkdirSync(COVERS_DIR, { recursive: true })
  const token = await getToken(id, secret)
  console.log('Got token. Fetching', GENRE_POINTS.length, 'covers…\n')

  const entries = []
  for (let i = 0; i < GENRE_POINTS.length; i++) {
    const g = GENRE_POINTS[i]
    const idx = String(i).padStart(2, '0')
    try {
      const url = await findCover(token, g.artist, g.song)
      if (!url) {
        console.warn(`  ${idx} ${g.artist} – ${g.song}: no cover found`)
        entries.push(null)
      } else {
        const file = `${idx}-${slug(g.artist)}.jpg`
        const buf = Buffer.from(await (await fetch(url)).arrayBuffer())
        writeFileSync(resolve(COVERS_DIR, file), buf)
        entries.push(file)
        console.log(`  ${idx} ${g.artist} – ${g.song} → ${file}`)
      }
    } catch (e) {
      console.warn(`  ${idx} ${g.artist} – ${g.song}: ${e.message}`)
      entries.push(null)
    }
    await new Promise((r) => setTimeout(r, 120)) // be gentle with the API
  }

  const lines = entries.map((f) => (f ? `  require('../../assets/covers/${f}'),` : '  null,'))
  writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/fetch-covers.mjs — do not edit.\n` +
      `// One cover per GENRE_POINTS index (null = not found → falls back to a colour).\n` +
      `export const COVERS = [\n${lines.join('\n')}\n]\n`,
  )
  const ok = entries.filter(Boolean).length
  console.log(`\nDone: ${ok}/${entries.length} covers → assets/covers/, wrote ${OUT.replace(ROOT + '/', '')}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})

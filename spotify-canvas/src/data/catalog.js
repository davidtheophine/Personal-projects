// Hand-authored cross-genre catalog (the POC "brain"). Platform-neutral data.
//
// Each song's `neighborIds` is an ordered pool of songs that RELATE to it (era,
// groove, mood, lineage, or scene) but span different facets, so the diversity
// picker can surface 5 that are "similar to the seed yet different from each
// other." Referential integrity + a >=5 neighbor floor are enforced by
// validateCatalog (see catalog.test.js). Ids are stable slugs, NOT Spotify ids.
//
// `artworkUrl` / `spotifyUri` are intentionally omitted: artwork is resolved at
// runtime (iTunes), and real full-track playback is a later layer. Absent those,
// cards render a generated cover and play a simulated progress bar.

